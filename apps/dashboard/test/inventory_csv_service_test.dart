import 'package:dashboard/features/inventory/services/inventory_csv_service.dart';
import 'package:dashboard/features/inventory/services/inventory_service.dart';
import 'package:flutter_test/flutter_test.dart';

// Columns of the live `cars` table (read back from the production API).
const _liveCarColumns = {
  'id', 'dealer_id', 'make', 'model', 'year', 'price', 'status', 'specs',
  'created_by', 'created_at', 'updated_at', 'mileage', 'color', 'transmission',
  'fuel_type', 'condition', 'purchase_price', 'retail_price', 'is_public',
  'features', 'reconditioning_notes',
};

void main() {
  final service = InventoryCsvService();

  test('headers are matched regardless of case, spacing, hyphens, or a BOM', () {
    expect(InventoryCsvService.normalizeHeader('﻿ Make '), 'make');
    expect(InventoryCsvService.normalizeHeader('Fuel Type'), 'fuel_type');
    expect(InventoryCsvService.normalizeHeader('PURCHASE-PRICE'), 'purchase_price');
  });

  test('enum aliases map to the values the live cars table accepts', () {
    final result = service.import(
      'MAKE, Model ,Year,Price,STATUS,Transmission,Fuel Type,Condition\n'
      'Toyota,Corolla,2020,"4,850,000", Active ,A/T,Gasoline,CPO\n'
      'Honda,Civic,2021,5200000,SOLD,m/t,EV,Used\n'
      'Suzuki,Swift,2019,2500000,reserved,Auto,CNG,Fair\n',
    );

    expect(result.errors, isEmpty);
    final [corolla, civic, swift] = result.validCars;
    expect(corolla.status, 'available');
    expect(corolla.transmission, 'automatic');
    expect(corolla.fuelType, 'petrol');
    expect(corolla.condition, 'excellent');
    expect(corolla.price, 4850000);
    expect(civic.status, 'sold');
    expect(civic.transmission, 'manual');
    expect(civic.fuelType, 'electric');
    expect(civic.condition, 'good');
    expect(swift.fuelType, 'cng');
    expect(swift.condition, 'fair');
  });

  test('insert payload uses only live column names and always carries dealer_id', () {
    final car = service
        .import('make,model,year,price,status,color,body type,condition,mileage\n'
            'Kia,Sportage,2023,"8,900,000",available,White,SUV,new,"12,000"\n')
        .validCars
        .single;

    final payload = InventoryService.buildInsertPayload(car, 'dealer-123');

    expect(_liveCarColumns.containsAll(payload.keys), isTrue,
        reason: 'unknown columns: ${payload.keys.toSet().difference(_liveCarColumns)}');
    expect(payload['dealer_id'], 'dealer-123');
    expect(payload['color'], 'White');
    expect(payload['condition'], 'excellent');
    expect(payload['mileage'], 12000);
    expect(payload['specs'], {'body_type': 'suv'});
    expect(payload.containsKey('id'), isFalse, reason: 'id is generated by the DB');
  });

  test('a row without body_type sends no specs, leaving the column default', () {
    final car = service
        .import('make,model,year,price,status\nToyota,Yaris,2022,4000000,available\n')
        .validCars
        .single;
    expect(InventoryService.buildInsertPayload(car, 'd').containsKey('specs'), isFalse);
  });

  test('common header spellings are aliased; unknown ones are reported, not dropped silently', () {
    final result = service.import(
      'Brand,Model,Year,Price,Status,KM,Colour,Gear,Fuel,Seats\n'
      'Honda,City,2021,4100000,available,"19,000",White,Auto,Petrol,5\n',
    );
    final car = result.validCars.single;
    expect(car.make, 'Honda');
    expect(car.mileage, 19000);
    expect(car.color, 'White');
    expect(car.transmission, 'automatic');
    expect(car.fuelType, 'petrol');
    expect(result.ignoredColumns, ['seats']);
  });

  test('optional columns may be missing; required ones may not', () {
    final ok = service.import('make,model,year,price,status\nToyota,Yaris,2022,4000000,available\n');
    expect(ok.errors, isEmpty);
    expect(ok.validCars.single.transmission, isNull);

    final missing = service.import('make,model,year\nToyota,Yaris,2022\n');
    expect(missing.validCars, isEmpty);
    expect(missing.errors.single.message, contains('price, status'));
  });

  test('an unrecognised value rejects only that row, naming accepted spellings', () {
    final result = service.import(
      'make,model,year,price,status,fuel_type\n'
      'Toyota,Corolla,2020,4850000,available,kerosene\n'
      'Honda,City,2021,4100000,available,hybrid\n',
    );
    expect(result.validCars.single.model, 'City');
    expect(result.errors.single.rowNumber, 2);
    expect(result.errors.single.message, contains('fuel_type "kerosene"'));
    expect(result.errors.single.message, contains('gasoline'));
  });
}
